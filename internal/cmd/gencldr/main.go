// Command gencldr generates metadata from the checked-in CLDR snapshot.
package main

import (
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

const release = "48.2"

type annotation struct {
	Code string `xml:"cp,attr"`
	Type string `xml:"type,attr"`
	Text string `xml:",chardata"`
}

type entry struct {
	name string
	tags []string
}

func parse(data []byte, entries map[string]entry) error {
	return parseLocale(data, entries, "en")
}

func parseLocale(data []byte, entries map[string]entry, locale string) error {
	var document struct {
		Identity struct {
			Language struct {
				Type string `xml:"type,attr"`
			} `xml:"language"`
		} `xml:"identity"`
		Annotations []annotation `xml:"annotations>annotation"`
	}
	if err := xml.Unmarshal(data, &document); err != nil {
		return err
	}
	if document.Identity.Language.Type != locale || len(document.Annotations) == 0 {
		return fmt.Errorf("expected %s CLDR annotations", locale)
	}
	for _, a := range document.Annotations {
		key := strings.ReplaceAll(a.Code, "\ufe0f", "")
		text := strings.TrimSpace(a.Text)
		if key == "" || text == "" || text == "↑↑↑" || text == "∅∅∅" {
			return fmt.Errorf("unresolved annotation for %q", a.Code)
		}
		e := entries[key]
		switch a.Type {
		case "tts":
			if e.name != "" && e.name != text {
				return fmt.Errorf("conflicting names for %q", key)
			}
			e.name = text
		case "":
			for _, tag := range strings.Split(text, "|") {
				tag = strings.TrimSpace(tag)
				if tag != "" && !slices.Contains(e.tags, tag) {
					e.tags = append(e.tags, tag)
				}
			}
		default:
			return fmt.Errorf("unknown annotation type %q", a.Type)
		}
		entries[key] = e
	}
	return nil
}

func generate(sourceDir string) ([]byte, error) {
	locales, err := loadLocales(sourceDir)
	if err != nil {
		return nil, err
	}
	entries := locales["en"]
	if len(entries) == 0 {
		return nil, fmt.Errorf("locale manifest is missing English annotations")
	}
	keys := make([]string, 0, len(entries))
	for key, e := range entries {
		if e.name == "" {
			return nil, fmt.Errorf("incomplete metadata for %q", key)
		}
		keys = append(keys, key)
	}
	slices.Sort(keys)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go generate; DO NOT EDIT.\n// Source: Unicode CLDR %s, English annotations and annotationsDerived.\n// Copyright © 1991-2025 Unicode, Inc.\n// SPDX-License-Identifier: Unicode-3.0\n// See third_party/unicode/LICENSE.txt and internal/cldr/README.md.\n\npackage ntemoji\n\n", release)
	fmt.Fprintln(&out, "var emojiNames = map[string]string{")
	for _, key := range keys {
		fmt.Fprintf(&out, "%q: %q,\n", key, entries[key].name)
	}
	fmt.Fprintln(&out, "}\n\nvar emojiTags = map[string][]string{")
	for _, key := range keys {
		if len(entries[key].tags) == 0 {
			continue
		}
		fmt.Fprintf(&out, "%q: %#v,\n", key, entries[key].tags)
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}

func main() {
	input := flag.String("input", "internal/cldr", "directory containing pinned CLDR XML files")
	output := flag.String("output", "metadata_generated.go", "generated English Go file")
	translations := flag.String("translations-output", "locales_generated.go", "generated translations Go file")
	emojiOutput := flag.String("emoji-output", "emoji_sequences_generated.go", "generated canonical emoji sequences")
	flag.Parse()
	data, err := generate(*input)
	if err == nil {
		err = os.WriteFile(*output, data, 0o644)
	}
	if err == nil {
		var translated []byte
		translated, err = generateTranslations(*input)
		if err == nil {
			err = os.WriteFile(*translations, translated, 0o644)
		}
	}
	if err == nil {
		var sequences []byte
		sequences, err = generateEmoji(*input)
		if err == nil {
			err = os.WriteFile(*emojiOutput, sequences, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
