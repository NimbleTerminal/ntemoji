package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

func generateEmoji(dir string) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(dir, "emoji-test.txt"))
	if err != nil {
		return nil, err
	}
	if fmt.Sprintf("%x", sha256.Sum256(data)) != "1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda" {
		return nil, fmt.Errorf("emoji-test.txt checksum mismatch")
	}
	entries := map[string]string{}
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line, _, _ := strings.Cut(scanner.Text(), "#")
		codes, status, ok := strings.Cut(line, ";")
		if !ok || strings.TrimSpace(status) != "fully-qualified" {
			continue
		}
		var glyph strings.Builder
		for _, code := range strings.Fields(codes) {
			cp, err := strconv.ParseInt(code, 16, 32)
			if err != nil {
				return nil, err
			}
			glyph.WriteRune(rune(cp))
		}
		emoji := glyph.String()
		entries[strings.ReplaceAll(emoji, "\ufe0f", "")] = emoji
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(entries))
	for key := range entries {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by go generate; DO NOT EDIT.\n// Source: Unicode Emoji 17.0 emoji-test.txt.\n// Copyright © 2025 Unicode, Inc.\n// SPDX-License-Identifier: Unicode-3.0\n// See third_party/unicode/LICENSE.txt.\n\npackage ntemoji\n\nvar canonicalEmoji = map[string]string{\n")
	for _, key := range keys {
		fmt.Fprintf(&out, "%q: %q,\n", key, entries[key])
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}
