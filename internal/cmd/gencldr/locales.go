package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
)

type localeSource struct {
	File   string `json:"file"`
	SHA256 string `json:"sha256"`
	Locale string `json:"locale"`
}

func loadLocales(dir string) (map[string]map[string]entry, error) {
	manifest, err := os.ReadFile(filepath.Join(dir, "sources.json"))
	if err != nil {
		return nil, err
	}
	var sources []localeSource
	if err := json.Unmarshal(manifest, &sources); err != nil {
		return nil, err
	}
	if len(sources) == 0 {
		return nil, fmt.Errorf("empty locale manifest")
	}
	locales := map[string]map[string]entry{}
	seen := map[string]bool{}
	for _, source := range sources {
		if !validBaseLocale(source.Locale) || source.File != filepath.Base(source.File) || seen[source.File] {
			return nil, fmt.Errorf("invalid or duplicate locale source: %+v", source)
		}
		seen[source.File] = true
		data, err := os.ReadFile(filepath.Join(dir, source.File))
		if err != nil {
			return nil, err
		}
		if fmt.Sprintf("%x", sha256.Sum256(data)) != source.SHA256 {
			return nil, fmt.Errorf("checksum mismatch for %s", source.File)
		}
		if locales[source.Locale] == nil {
			locales[source.Locale] = map[string]entry{}
		}
		if err := parseLocale(data, locales[source.Locale], source.Locale); err != nil {
			return nil, fmt.Errorf("%s: %w", source.File, err)
		}
	}
	return locales, nil
}

// The runtime currently supports complete base-language tables only. Reject
// regional/script tags explicitly rather than emitting invalid Go identifiers
// or silently ignoring CLDR inheritance.
func validBaseLocale(locale string) bool {
	if len(locale) < 2 || len(locale) > 3 {
		return false
	}
	for _, r := range locale {
		if r < 'a' || r > 'z' {
			return false
		}
	}
	return true
}

func generateTranslations(dir string) ([]byte, error) {
	locales, err := loadLocales(dir)
	if err != nil {
		return nil, err
	}
	delete(locales, "en")
	names := make([]string, 0, len(locales))
	for locale := range locales {
		names = append(names, locale)
	}
	slices.Sort(names)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go generate; DO NOT EDIT.\n// Source: Unicode CLDR %s annotations and annotationsDerived.\n// Copyright © 1991-2025 Unicode, Inc.\n// SPDX-License-Identifier: Unicode-3.0\n// See third_party/unicode/LICENSE.txt and internal/cldr/README.md.\n\npackage ntemoji\n\n", release)
	for _, locale := range names {
		entries := locales[locale]
		keys := make([]string, 0, len(entries))
		for key, e := range entries {
			if e.name == "" {
				return nil, fmt.Errorf("%s: missing name for %q", locale, key)
			}
			keys = append(keys, key)
		}
		slices.Sort(keys)
		fmt.Fprintf(&out, "var emojiLocale%s = map[string]localizedMetadata{\n", locale)
		for _, key := range keys {
			e := entries[key]
			fmt.Fprintf(&out, "%q: {Name: %q, Tags: %#v},\n", key, e.name, e.tags)
		}
		fmt.Fprintln(&out, "}")
	}
	fmt.Fprintln(&out, "var emojiLocales = map[string]map[string]localizedMetadata{")
	for _, locale := range names {
		fmt.Fprintf(&out, "%q: emojiLocale%s,\n", locale, locale)
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}
